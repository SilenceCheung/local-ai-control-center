export function resolveLang(pref: string, navigatorLang?: string): ResolvedLang {
  if (pref === "en") return "en";
  if (pref === "zh-Hans") return "zh-Hans";
  const nav = (navigatorLang || (typeof navigator !== "undefined" ? navigator.language : "en") || "en")
    .toLowerCase()
    .replace("_", "-");
  if (nav === "zh" || nav.startsWith("zh-")) return "zh-Hans";
  return "en";
}

export function catalog(resolved: ResolvedLang): Record<MsgKey, string> {
  return resolved === "zh-Hans" ? ZH : EN;
}

export function formatMsg(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, k: string) => (vars[k] == null ? "" : String(vars[k])));
}
